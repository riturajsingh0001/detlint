package schema

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

type fieldStats struct {
	count    int
	types    map[FieldType]int
	values   map[string]bool
	hasNull  bool
	hasArray bool
}

// Learn infers a candidate schema from decoded sample records.
func Learn(records []map[string]any, name, product, service string) *LogSource {
	total := len(records)
	stats := map[string]*fieldStats{}
	for _, rec := range records {
		flat := map[string]any{}
		flatten("", rec, flat)
		for k, v := range flat {
			st := stats[k]
			if st == nil {
				st = &fieldStats{types: map[FieldType]int{}, values: map[string]bool{}}
				stats[k] = st
			}
			st.count++
			if v == nil {
				st.hasNull = true
				continue
			}
			switch val := v.(type) {
			case bool:
				st.types[TypeBool]++
				st.values[strconv.FormatBool(val)] = true
			case float64:
				if val == float64(int64(val)) {
					st.types[TypeInt]++
					st.values[strconv.FormatInt(int64(val), 10)] = true
				} else {
					st.types[TypeFloat]++
					st.values[strconv.FormatFloat(val, 'f', -1, 64)] = true
				}
			case string:
				st.types[TypeString]++
				st.values[val] = true
			case []any:
				st.hasArray = true
				st.types[TypeString]++
			default:
				st.types[TypeString]++
				st.values[fmt.Sprint(val)] = true
			}
		}
	}

	keys := make([]string, 0, len(stats))
	for k := range stats {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		if stats[keys[i]].count != stats[keys[j]].count {
			return stats[keys[i]].count > stats[keys[j]].count
		}
		return keys[i] < keys[j]
	})

	s := &LogSource{Name: name, Product: product, Service: service}
	for _, k := range keys {
		st := stats[k]
		f := Field{Name: k, Type: dominantType(st), Required: total > 0 && st.count == total}
		if !st.hasArray && !st.hasNull && len(st.values) > 0 && len(st.values) <= 15 {
			for v := range st.values {
				f.Enum = append(f.Enum, v)
			}
			sort.Slice(f.Enum, func(i, j int) bool {
				if len(f.Enum[i]) != len(f.Enum[j]) {
					return len(f.Enum[i]) < len(f.Enum[j])
				}
				return f.Enum[i] < f.Enum[j]
			})
		}
		s.Fields = append(s.Fields, f)
	}
	s.Finalize()
	return s
}

func dominantType(st *fieldStats) FieldType {
	best, bestCount := TypeString, -1
	for _, t := range []FieldType{TypeInt, TypeFloat, TypeBool, TypeString} {
		if st.types[t] > bestCount {
			best, bestCount = t, st.types[t]
		}
	}
	return best
}

func flatten(prefix string, m map[string]any, out map[string]any) {
	for k, v := range m {
		key := k
		if prefix != "" {
			key = prefix + "." + k
		}
		if child, ok := v.(map[string]any); ok {
			flatten(key, child, out)
			continue
		}
		out[key] = v
	}
}

// MarshalYAML renders a schema in the format detlint loads.
func MarshalYAML(s *LogSource) []byte {
	var b strings.Builder
	b.WriteString("# Generated by detlint schema learn\n")
	fmt.Fprintf(&b, "name: %s\n", yamlString(s.Name))
	if s.Product != "" {
		fmt.Fprintf(&b, "product: %s\n", yamlString(s.Product))
	}
	if s.Service != "" {
		fmt.Fprintf(&b, "service: %s\n", yamlString(s.Service))
	}
	if s.Category != "" {
		fmt.Fprintf(&b, "category: %s\n", yamlString(s.Category))
	}
	if s.Description != "" {
		fmt.Fprintf(&b, "description: %s\n", yamlString(s.Description))
	}
	b.WriteString("fields:\n")
	for _, f := range s.Fields {
		fmt.Fprintf(&b, "  - name: %s\n", yamlString(f.Name))
		fmt.Fprintf(&b, "    type: %s\n", f.Type)
		if f.Required {
			b.WriteString("    required: true\n")
		}
		if len(f.Enum) > 0 {
			vals := make([]string, len(f.Enum))
			for i, v := range f.Enum {
				vals[i] = yamlString(v)
			}
			fmt.Fprintf(&b, "    enum: [%s]\n", strings.Join(vals, ", "))
		}
		if f.Description != "" {
			fmt.Fprintf(&b, "    description: %s\n", yamlString(f.Description))
		}
	}
	return []byte(b.String())
}

func yamlString(s string) string {
	if s == "" {
		return `""`
	}
	safe := true
	for _, r := range s {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("._-/", r)) {
			safe = false
			break
		}
	}
	if safe {
		return s
	}
	return strconv.Quote(s)
}
